const normalizeLanguageCode = (code?: string): string => {
  if (!code) return 'fr';
  const prefix = code.toLowerCase().split('-')[0].split('_')[0];
  if (['fr', 'en', 'ar', 'zh'].includes(prefix)) {
    return prefix;
  }
  return 'fr';
};

export const changeLanguage = (lang: string) => {
  const norm = normalizeLanguageCode(lang);
  i18n.changeLanguage(norm);
  const dir = norm === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.dir = dir;
  document.documentElement.lang = norm;
  localStorage.setItem('i18nextLng', norm);
};

i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources,
    fallbackLng: 'fr',
    supportedLngs: ['fr', 'en', 'ar', 'zh'],
    load: 'languageOnly',
    interpolation: {
      escapeValue: false,
    },
    detection: {
      order: ['localStorage', 'navigator'],
      caches: ['localStorage'],
      lookupLocalStorage: 'i18nextLng',
    },
    react: {
      useSuspense: false,
    },
  });

// Keep document dir & lang in sync with i18n at all times
i18n.on('languageChanged', (lng) => {
  const norm = normalizeLanguageCode(lng);
  const dir = norm === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.dir = dir;
  document.documentElement.lang = norm;
});

// Initial synchronization
const initialNorm = normalizeLanguageCode(i18n.language);
document.documentElement.dir = initialNorm === 'ar' ? 'rtl' : 'ltr';
document.documentElement.lang = initialNorm;

export default i18n;
